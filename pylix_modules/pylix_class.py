# variables used in the Bloch wave calculation
@dataclass
class Bloch:
    """
    Beam pool and pixel-level Bloch-wave quantities.

    Attributes
    ----------
    n_hkl            : int  — total number of beams in the pool
    n_out            : int  — number of output beams (subset of n_hkl)

    hkl_indices      : ndarray (n_hkl, 3) int
        Integer Miller indices for every beam in the pool, in the same order
        as the rows/columns of ug_matrix, s_g, etc.
        Used by build_atom_ug_grad to compute h_diff[m,n] = hkl[m] − hkl[n].

    hkl_output       : ndarray (n_out,) int
        Indices into hkl_indices for the requested output beams.

    g_pool           : ndarray (n_hkl, 3)  — g-vectors (1/Å, microscope frame)
    g_pool_mag       : ndarray (n_hkl,)    — |g| (1/Å)
    g_matrix         : ndarray (n_hkl, n_hkl, 3)  — g_m − g_n vectors
    g_dot_norm       : ndarray (n_hkl,)    — g · n̂ (surface normal component)

    ug_matrix        : ndarray (n_hkl, n_hkl) complex  — optical potential
    s_g              : ndarray (imgX, imgY, n_hkl)     — deviation parameters
    k_dot_n          : ndarray (imgX, imgY)             — k · n̂ per pixel
    tilted_k         : ndarray (imgX, imgY, 3)          — k-vector per pixel

    big_k_mag        : float  — |K| in crystal (Å⁻¹)
    big_k            : ndarray (3,)  — K-vector in microscope frame
    relativistic_correction : float  — Lorentz factor γ
    electron_velocity       : float  — v (m/s)
    """
    electron_velocity: float = 0.0
    relativistic_correction: float = 0.0
    big_k: NDArray[np.floating] | None = None
    big_k_mag: float = 0.0
    tilted_k: NDArray[np.floating] | None = None
    k_dot_n: NDArray[np.floating] | None = None
    k_dot_n_pix: NDArray[np.floating] | None = None
    n_hkl: int = 0
    n_out: int = 0
    hkl_indices: NDArray[np.integer] | None = None
    hkl_output: NDArray[np.integer] | None = None
    g_pool: NDArray[np.floating] | None = None
    g_pool_mag: NDArray[np.floating] | None = None
    g_matrix: NDArray[np.floating] | None = None
    uniq_gmag: NDArray[np.floating] | None = None
    ug_matrix: NDArray[np.floating] | None = None
    g_dot_norm: NDArray[np.floating] | None = None
    s_g: NDArray[np.floating] | None = None
    s_g_pix: NDArray[np.floating] | None = None
    wave_function: NDArray[np.complex128] | None = None
    strong_beam: NDArray[np.integer] | None = None
