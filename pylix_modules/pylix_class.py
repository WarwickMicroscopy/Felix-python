# classes derived from the .cif file
@dataclass
class Crystal:
    """
    Unit-cell geometry and space-group symmetry.

    Attributes set at construction
    --------------------------------
    (all populated by CIF parsing and px.reference_frames)

    cell_a, cell_b, cell_c      : float  — lattice parameters (Å)
    cell_alpha, cell_beta,
    cell_gamma                  : float  — lattice angles (radians)
    cell_volume                 : float  — unit-cell volume (Å³)
    mott                        : float  — Mott–Bethe prefactor
    chemical_formula            : str

    symmetry_matrix : ndarray, shape (n_symops, 3, 3)
        Rotation part of each symmetry operation (fractional coordinates).
        symmetry_matrix[i] is the 3×3 matrix R_i for operation i.
        Used by build_atom_ug_grad to rotate the movement vector v:
            R_i @ v  →  effective displacement direction for cell atom k.

    symmetry_vector : ndarray, shape (n_symops, 3)
        Translation part of each symmetry operation (fractional coordinates).
        symmetry_vector[i] is the translation t_i for operation i.

    norm_dir_m   : ndarray (3,)  — surface normal in microscope frame
    x_dir_m      : ndarray (3,)  — x-direction in microscope frame
    y_dir_m      : ndarray (3,)  — y-direction in microscope frame
    a_vec_m, b_vec_m, c_vec_m   : ndarray (3,)  — lattice vectors in
                                   microscope frame
    """
    space_group: str = ""
    chemical_formula: str = ""
    lattice_type: str = ""
    space_group_number: int = 0
    symmetry_matrix: NDArray[np.integer] | None = None
    symmetry_vector: NDArray[np.floating] | None = None
    cell_a: float = 0.0
    cell_b: float = 0.0
    cell_c: float = 0.0
    cell_alpha: float = 0.0
    cell_beta: float = 0.0
    cell_gamma: float = 0.0
    cell_volume: float = 0.0
    a_vec_m: NDArray[np.floating] | None = None
    b_vec_m: NDArray[np.floating] | None = None
    c_vec_m: NDArray[np.floating] | None = None
    ar_vec_m: NDArray[np.floating] | None = None
    br_vec_m: NDArray[np.floating] | None = None
    cr_vec_m: NDArray[np.floating] | None = None
    norm_dir_m: NDArray[np.floating] | None = None
    t_mat_o2m: NDArray[np.floating] | None = None
    t_mat_c2o: NDArray[np.floating] | None = None
    t_mat_cr2mr: NDArray[np.floating] | None = None
    # kappa model
