# -*- coding: utf-8 -*-
"""
pylix_class.py

Dataclass definitions for the pylix Bloch-wave simulation and refinement code.

Class hierarchy and responsibilities
-------------------------------------
Crystal  (xtal)
    Everything derived purely from the CIF unit cell: lattice parameters,
    space-group symmetry operations, and reference-frame transformations.
    Owns the symmetry_matrix / symmetry_vector arrays used in the gradient
    calculation (one rotation matrix and one translation vector per symop).

Basis  (basis)
    The asymmetric unit: the minimal set of atoms needed to generate the
    full unit cell when the symmetry operations in xtal are applied.
    Owns scattering-factor parameters (kappa, pv, f_g), occupancies, and
    anisotropic displacement parameters in the CIF/fractional frame.

Cell  (cell)
    The full unit cell: all atoms generated by applying xtal's symmetry
    operations to basis.  Owns fractional coordinates, Cartesian
    coordinates (in the microscope reference frame), anisotropic
    displacement parameters rotated into the microscope frame, and — for
    the analytical gradient — the two index arrays that record which basis
    atom and which symmetry operation generated each cell atom:
        basis_atom_index[k]  →  index into basis (0…basis.n_atoms−1)
        symop_index[k]       →  index into xtal.symmetry_matrix

HKL  (hkl)
    Miller indices read from felix.hkl (the output reflections requested by
    the user).  Distinct from the full beam pool built in Bloch.

Bloch  (bloch)
    Everything derived from the beam-pool construction and the pixel-by-pixel
    deviation-parameter calculation: g-vectors, the Ug matrix, deviation
    parameters, wave vectors, and the hkl_indices array (integer Miller
    indices for each beam in the pool, shape (n_hkl, 3)), which is needed
    by build_atom_ug_grad to form the h_diff differences.

RunControl  (rc)
    All parameters read from felix.inp, refinement state, and the
    atom_refine_vec array (shape (n_variables, 3)) that records the allowed
    fractional-coordinate movement direction for each coordinate refinement
    variable — set by atom_move / preferred_basis in pylix.py.

CBED  (cbed)
    Simulation outputs and their comparison with experiment:
        lacbed_sim   [n_thickness, imgX, imgY, n_out]   — simulated intensities
        lacbed_expt  [imgX, imgY, n_out]                — experimental patterns
        lacbed_diff  [n_thickness, imgX, imgY, n_out]   — sim − expt
        lacbed_sig   [n_variables, imgX, imgY, n_out]   — sensitivity images dI/dp
        lacbed_mask  [n_variables, imgX, imgY, n_out]   — thresholded sensitivity
        lacbed_grad  [n_grad_vars, n_thickness, imgX, imgY, n_out]
                                                        — analytical gradient dI/dp
                     n_grad_vars = number of coordinate refinement variables
                     (indexed by position in grad_var_indices, not by var_idx)
"""
import numpy as np
