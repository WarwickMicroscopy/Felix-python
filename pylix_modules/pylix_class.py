# variables output
@dataclass
class Cbed:
    """
    Simulation outputs and experimental data.

    Array shapes
    ------------
    lacbed_sim   : (n_thickness, imgX, imgY, n_out)      simulated intensities
    lacbed_expt  : (imgX, imgY, n_out)                   experimental patterns
    lacbed_expt_raw : (imgX, imgY, n_out)                unmodified experiment
    lacbed_diff  : (n_thickness, imgX, imgY, n_out)      sim − expt (normalised)
    lacbed_ref   : (imgX, imgY, n_out)                   reference simulation
    lacbed_sig   : (n_variables, imgX, imgY, n_out)      sensitivity dI/dp
    lacbed_mask  : (n_variables, imgX, imgY, n_out)      thresholded sensitivity

    lacbed_grad  : (n_grad_vars, n_thickness, imgX, imgY, n_out)
        Analytical gradient dI/dp for each coordinate refinement variable,
        already projected onto the allowed movement direction v.
        n_grad_vars = len(grad_var_indices) as built in simulate().
        The mapping from axis-0 index to var_idx is given by
        grad_var_indices (stored in simulate's shared_data).

    lacbed_mask_i, lacbed_mask_j : used in correlation analysis (mode X).
    correlation_matrix           : (n_correlations, n_out).
    """
    # arrays of images
    lacbed_sim: NDArray[np.floating] | None = None  # simulation
    lacbed_expt_raw: NDArray[np.floating] | None = None  # experiment
    lacbed_expt: NDArray[np.floating] | None = None  # experiment, processed
    # lacbed_grad gives gradient images for atomic coordinates
    # shape [n_grad_vars, n_thickness, imgX, imgY, n_out]
    lacbed_grad: NDArray[np.floating] | None = None
    lacbed_diff: NDArray[np.floating] | None = None  # difference sim:expt
    lacbed_ref: NDArray[np.floating] | None = None  # reference used for sig
    lacbed_sig: NDArray[np.floating] | None = None  # signature 
    lacbed_mask: NDArray[np.floating] | None = None  # masks
    lacbed_mask_i: NDArray[np.floating] | None = None  # masks for i
    lacbed_mask_j: NDArray[np.floating] | None = None  # masks for j
    correlation_matrix: NDArray[np.floating] | None = None  # correlations 
    # figures of merit, one per image
    diff_max: NDArray[np.floating] | None = None  # max difference ()
    diff_mean: NDArray[np.floating] | None = None


