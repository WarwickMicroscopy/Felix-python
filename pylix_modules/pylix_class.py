@dataclass
class Cell:
    """
    Full unit cell — all atoms after symmetry expansion.

    The symmetry expansion is performed by px.unique_atom_positions, which
    applies every operation in xtal.symmetry_matrix / symmetry_vector to
    each basis atom.  Two index arrays record the provenance of each cell
    atom:

    basis_atom_index : ndarray (n_atoms,) int
        basis_atom_index[k] = index of the basis atom (0…basis.n_atoms−1)
        that generated cell atom k.  Used in build_atom_ug_grad to select
        which cell atoms contribute to the gradient of a given refinement
        variable.

    symop_index : ndarray (n_atoms,) int
        symop_index[k] = index of the symmetry operation (row of
        xtal.symmetry_matrix) that generated cell atom k.  Used in
        build_atom_ug_grad to look up the rotation matrix R_k.

    All other attributes
    --------------------
    n_atoms          : int
    atom_label       : list of str
    atom_name        : list of str
    atomic_number    : ndarray (n_atoms,) int
    atom_position    : ndarray (n_atoms, 3)  fractional coords (CIF frame)
    atom_coordinate  : ndarray (n_atoms, 3)  Cartesian (microscope frame, Å)
    occupancy        : ndarray (n_atoms,)
    u_aniso          : ndarray (n_atoms, 3, 3)  ADPs (CIF frame)
    u_aniso_m        : ndarray (n_atoms, 3, 3)  ADPs (microscope frame)
    f_g              : ndarray (n_atoms, n_hkl, n_hkl) complex
                       scattering factors on the g-difference grid,
                       populated by px.Fg_matrix
    """
    n_atoms: int = 0
    atom_label: list | None = None
    atom_name: list | None = None
    oxno: NDArray[np.integer] | None = None
    atomic_number: NDArray[np.integer] | None = None
    wyckoff: list | None = None
    atom_position: NDArray[np.floating] | None = None  # in cell
    atom_coordinate: NDArray[np.floating] | None = None  # in microscope frame
    occupancy: NDArray[np.floating] | None = None
    mult_occ: NDArray[np.integer] | None = None
    u_aniso: NDArray[np.floating] | None = None  # in cell
    u_aniso_m: NDArray[np.floating] | None = None  # in microscope frame
    u_iso: NDArray[np.floating] | None = None
    B_iso: NDArray[np.floating] | None = None
    # basis_atom_index[k] = which basis atom generated cell atom k
    basis_atom_index: NDArray[np.integer] | None = None
    # symop_index[k] = which symmetry operation was applied
    symop_index:      NDArray[np.integer] | None = None
    atom_delta: NDArray[np.floating] | None = None
    f_g: NDArray[np.complex128] | None = None
    # kappa model
    kappa: NDArray[np.floating] | None = None
    core: NDArray[np.floating] | None = None
    valence: NDArray[np.floating] | None = None
    pc: NDArray[np.floating] | None = None
    pv: NDArray[np.floating] | None = None
    mean_sq_r2: NDArray[np.floating] | None = None


